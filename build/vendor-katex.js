/*
 * Copies KaTeX's stylesheet and fonts from node_modules into css/katex/,
 * where the page templates load them as static files (the JS goes into the
 * bundle as a chunk of its own, see src/util/katex-loader.js). Only the
 * woff2 fonts are kept and the @font-face rules are cut down to them: every
 * browser the bundle targets reads woff2, and the woff and ttf copies would
 * triple the size of the repository for nothing.
 *
 *   node build/vendor-katex.js          # write css/katex/
 *   node build/vendor-katex.js --check  # exit 1 if css/katex/ differs from the package
 *
 * Run it after `npm install` changed the KaTeX version and commit the result.
 */
const fs = require('fs')
const path = require('path')

const root = path.join(__dirname, '..')
const src = path.join(root, 'node_modules', 'katex')
const dst = path.join(root, 'css', 'katex')
const check = process.argv.includes('--check')

const version = JSON.parse(fs.readFileSync(path.join(src, 'package.json'), 'utf8')).version

// The expected files: path relative to css/katex -> Buffer.
const files = new Map()

let css = fs.readFileSync(path.join(src, 'dist', 'katex.min.css'), 'utf8')
const before = (css.match(/url\(fonts\/[^)]+\.woff2\)/g) || []).length
css = css.replace(
	/url\(fonts\/([^)]+\.woff2)\) format\("woff2"\)(?:,url\(fonts\/[^)]+\) format\("[^"]+"\))*/g,
	'url(fonts/$1) format("woff2")',
)
if (before === 0 || /\.(woff|ttf)\)/.test(css)) {
	console.error('vendor-katex: the @font-face rules of katex.min.css do not look as expected')
	process.exit(2)
}
files.set('katex.min.css', Buffer.from(
	`/* KaTeX ${version} (MIT, https://katex.org), woff2 only; generated by build/vendor-katex.js */\n` + css,
))
files.set('LICENSE', fs.readFileSync(path.join(src, 'LICENSE')))
for (const name of fs.readdirSync(path.join(src, 'dist', 'fonts')).sort()) {
	if (name.endsWith('.woff2')) {
		files.set(path.join('fonts', name), fs.readFileSync(path.join(src, 'dist', 'fonts', name)))
	}
}

function listDir(dir, base = dir) {
	const out = []
	if (!fs.existsSync(dir)) return out
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, entry.name)
		if (entry.isDirectory()) out.push(...listDir(p, base))
		else out.push(path.relative(base, p))
	}
	return out.sort()
}

if (check) {
	const problems = []
	for (const [rel, want] of files) {
		const p = path.join(dst, rel)
		if (!fs.existsSync(p)) problems.push('missing: ' + rel)
		else if (!fs.readFileSync(p).equals(want)) problems.push('differs: ' + rel)
	}
	for (const rel of listDir(dst)) {
		if (!files.has(rel)) problems.push('stray: ' + rel)
	}
	if (problems.length) {
		console.error('vendor-katex: css/katex/ does not match katex ' + version + ' from node_modules:\n  ' + problems.join('\n  ')
			+ '\nRun `node build/vendor-katex.js` and commit the result.')
		process.exit(1)
	}
	console.log('vendor-katex: css/katex/ matches katex ' + version + ' (' + files.size + ' files)')
} else {
	fs.rmSync(dst, { recursive: true, force: true })
	for (const [rel, data] of files) {
		fs.mkdirSync(path.dirname(path.join(dst, rel)), { recursive: true })
		fs.writeFileSync(path.join(dst, rel), data)
	}
	console.log('vendor-katex: wrote ' + files.size + ' files of katex ' + version + ' to css/katex/')
}
